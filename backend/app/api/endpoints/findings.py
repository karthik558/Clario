from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.database.session import get_db
from app.models.entities import Document, Finding
from app.schemas.dtos import FindingCreate, FindingUpdate, FindingResponse
from app.services.finding_service import FindingService
from app.services.compare_service import CompareService

router = APIRouter()

@router.get("/findings", response_model=List[FindingResponse])
def list_findings(
    category: Optional[str] = None,
    status: Optional[str] = None,
    severity: Optional[str] = None,
    db: Session = Depends(get_db)
):
    findings = FindingService.list_findings(db, category=category, status=status, severity=severity)
    return [FindingResponse.from_orm(f) for f in findings]

@router.post("/findings", response_model=FindingResponse)
def create_finding(data: FindingCreate, db: Session = Depends(get_db)):
    finding = FindingService.create_finding(data, db)
    return FindingResponse.from_orm(finding)

@router.get("/findings/{finding_id}", response_model=FindingResponse)
def get_finding(finding_id: str, db: Session = Depends(get_db)):
    finding = FindingService.get_finding(finding_id, db)
    if not finding:
        raise HTTPException(status_code=404, detail="Finding not found")
    return FindingResponse.from_orm(finding)

@router.patch("/findings/{finding_id}", response_model=FindingResponse)
def update_finding(finding_id: str, data: FindingUpdate, db: Session = Depends(get_db)):
    finding = FindingService.update_finding(finding_id, data, db)
    if not finding:
        raise HTTPException(status_code=404, detail="Finding not found")
    return FindingResponse.from_orm(finding)

@router.delete("/findings/{finding_id}")
def delete_finding(finding_id: str, db: Session = Depends(get_db)):
    success = FindingService.delete_finding(finding_id, db)
    if not success:
        raise HTTPException(status_code=404, detail="Finding not found")
    return {"message": "Finding deleted successfully"}

@router.post("/findings/scan")
def trigger_contradiction_scan(db: Session = Depends(get_db)):
    """
    Automated scan across document pairs to detect candidate contradictions
    and automatically create reviewable findings.
    """
    docs = db.query(Document).filter(Document.status == "READY").all()
    created_count = 0
    if len(docs) < 2:
        return {"scanned_pairs": 0, "created_findings": 0, "message": "Need at least 2 indexed documents to run contradiction scan."}

    for i in range(len(docs)):
        for j in range(i + 1, len(docs)):
            doc_a = docs[i]
            doc_b = docs[j]
            try:
                comp = CompareService.compare_documents(doc_a.id, doc_b.id, db)
                for cand in comp.contradiction_candidates:
                    # Check if finding already exists
                    existing = db.query(Finding).filter(
                        Finding.title == cand.topic,
                        Finding.doc_a_id == doc_a.id,
                        Finding.doc_b_id == doc_b.id
                    ).first()
                    if not existing:
                        f = FindingCreate(
                            category="possible_contradiction",
                            title=cand.topic,
                            description=cand.explanation,
                            severity="high" if cand.confidence == "high" else "medium",
                            status="open",
                            doc_a_id=doc_a.id,
                            doc_a_title=doc_a.title,
                            doc_a_page=cand.page_a,
                            doc_a_quote=cand.statement_a,
                            doc_b_id=doc_b.id,
                            doc_b_title=doc_b.title,
                            doc_b_page=cand.page_b,
                            doc_b_quote=cand.statement_b,
                            reviewer_notes="Automatically generated by Clario Contradiction Detection Engine."
                        )
                        FindingService.create_finding(f, db)
                        created_count += 1
            except Exception:
                continue

    return {
        "scanned_pairs": (len(docs) * (len(docs) - 1)) // 2,
        "created_findings": created_count,
        "message": f"Scan completed. Generated {created_count} new candidate finding(s)."
    }
